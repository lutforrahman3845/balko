function getRandomSocialLinks(): Record<string, string> {
  const platforms = [
    'linkedin',
    'twitter',
    'github',
    'instagram',
    'facebook',
    'youtube',
    'stackoverflow',
    'bluesky',
    'pinterest',
    'snapchat',
    'twitch',
    'slack',
    'dribbble',
    'behance',
    'spotify',
    'soundcloud',
    'patreon',
    'mastodon',
    'tumblr',
    'quora',
    'signal',
    'viber',
    'line',
    'wechat',
    'kakaotalk',
    'producthunt',
    'figma',
    'tiktok',
    'reddit',
    'threads',
    'whatsapp',
    'telegram',
    'discord',
    'medium',
  ];
  const selected = new Set<string>();

  while (selected.size < 7) {
    const randomIndex = Math.floor(Math.random() * platforms.length);
    selected.add(platforms[randomIndex]);
  }

  return Array.from(selected).reduce(
    (acc, platform) => {
      acc[platform] = `https://${platform}.com/contact_123`;
      return acc;
    },
    {} as Record<string, string>,
  );
}

